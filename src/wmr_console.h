/*
 * wmr_console.h - serial console: single-key commands and the periodic
 * statistics line.
 */

#ifndef WMR_CONSOLE_H
#define WMR_CONSOLE_H

#include <stdint.h>

/* Install the stdin handler (if the port has stdin) and the stats timer. */
void wmr_console_init(void);

/* Print the command list. Called when the stack reaches the working state. */
void wmr_console_show_usage(void);

/* HCI events: show usage once the stack is up. */
void wmr_console_on_hci_event(uint8_t *packet, uint16_t size);

#endif /* WMR_CONSOLE_H */
